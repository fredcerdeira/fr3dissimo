#!/usr/bin/env node
// Generates site/css/tokens.css from tokens/*.tokens.json.
//
// Zero dependencies (Node 20+). Usage:
//   node scripts/build-tokens.mjs          write site/css/tokens.css
//   node scripts/build-tokens.mjs --check  fail if the committed file is out of date
//
// Output order:
//   1. Theme primitives, one block per theme. Classic is also the default (:root).
//   2. Surface roles: Asphalt on :root, Paper on .paper.
//   3. Shared scale on :root.
//   4. Legacy names used by site/css/styles.css, on :root.

import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SOURCES = {
  primitives: 'tokens/theme-primitives.tokens.json',
  surface: 'tokens/surface.tokens.json',
  shared: 'tokens/shared.tokens.json',
};
const OUT = 'site/css/tokens.css';
const FONTS_OUT = 'site/theme-fonts.js';

class BuildError extends Error {}

async function readJson(rel) {
  return JSON.parse(await readFile(path.join(ROOT, rel), 'utf8'));
}

// Yields every leaf token ({ $value, ... }) with its dotted path, skipping $-prefixed metadata.
function* tokensIn(node, trail = []) {
  for (const [key, value] of Object.entries(node)) {
    if (key.startsWith('$')) continue;
    if (value && typeof value === 'object') {
      if ('$value' in value) yield { path: [...trail, key].join('.'), token: value };
      else yield* tokensIn(value, [...trail, key]);
    }
  }
}

// Resolves "{a.b}" to var(--css) plus the optional fallback stack. Plain values pass through.
function resolveRef(raw, index, where) {
  const m = /^\{([^}]+)\}$/.exec(raw);
  if (!m) return raw;
  const target = index.get(m[1]);
  if (!target) throw new BuildError(`${where}: reference {${m[1]}} is not in theme-primitives`);
  return `var(${target.$css})${target.$fallback ?? ''}`;
}

function primitiveValue(token, mode, where) {
  if (!(mode in token.$value)) throw new BuildError(`${where}: no value for mode "${mode}"`);
  const v = token.$value[mode];
  return token.$type === 'dimension' ? `${v}${token.$unit}` : String(v);
}

function block(selector, lines) {
  return [`${selector} {`, ...lines.map((l) => `  ${l}`), '}', ''];
}

// Font stylesheets per theme, read by site/theme.js when the theme changes.
function buildFontsJs(primitives) {
  const fonts = primitives.$fonts ?? {};
  const map = {};
  for (const mode of primitives.$modes) {
    const slug = mode.toLowerCase();
    if (!Array.isArray(fonts[slug])) throw new BuildError(`$fonts has no list for "${slug}"`);
    map[slug] = fonts[slug];
  }
  return [
    '// Generated by scripts/build-tokens.mjs from tokens/theme-primitives.tokens.json. Do not edit by hand.',
    `window.FR3_THEME_FONTS = ${JSON.stringify(map, null, 2)};`,
    '',
  ].join('\n');
}

function buildCss({ primitives, surface, shared }) {
  const out = [
    '/* Generated by scripts/build-tokens.mjs from tokens/*.tokens.json. Do not edit by hand. */',
    '',
  ];

  // 1. Theme primitives: one block per Figma mode.
  const primTokens = [...tokensIn(primitives)];
  const index = new Map(primTokens.map(({ path: p, token }) => [p, token]));
  // The first mode is the default on :root. Other modes use :root[data-theme] (specificity 0,2,0)
  // so that <html data-theme="..."> beats the default regardless of source order.
  primitives.$modes.forEach((mode, i) => {
    const slug = mode.toLowerCase();
    const selector =
      i === 0 ? `:root, [data-theme="${slug}"]` : `:root[data-theme="${slug}"], [data-theme="${slug}"]`;
    const lines = primTokens.map(({ path: p, token }) => {
      if (!token.$css) throw new BuildError(`${p}: missing $css`);
      return `${token.$css}: ${primitiveValue(token, mode, p)};`;
    });
    out.push(...block(selector, lines));
  });

  // 2. Surface roles. Asphalt is the default on :root, Paper applies inside .paper.
  const surfaceTokens = [...tokensIn(surface)];
  const surfaceSelectors = { Asphalt: ':root', Paper: '.paper' };
  for (const mode of surface.$modes) {
    const selector = surfaceSelectors[mode];
    if (!selector) throw new BuildError(`surface mode "${mode}" has no selector in build-tokens.mjs`);
    const lines = surfaceTokens.map(({ path: p, token }) => {
      if (!(mode in token.$value)) throw new BuildError(`${p}: no value for mode "${mode}"`);
      return `${token.$css}: ${resolveRef(token.$value[mode], index, `${p} [${mode}]`)};`;
    });
    if (mode === 'Asphalt') {
      // 3. Shared scale, theme-independent, on :root with the Asphalt roles.
      for (const { path: p, token } of tokensIn(shared)) {
        lines.push(`${token.$css}: ${primitiveValue(token, 'Value', p)};`);
      }
    }
    out.push(...block(selector, lines));
  }

  // 4. Legacy names used by site/css/styles.css. Fixed values, so today's stylesheet renders the same.
  const legacy = Object.entries(surface.$legacy ?? {})
    .filter(([name]) => name.startsWith('--'))
    .map(([name, ref]) => `${name}: ${resolveRef(ref, index, `$legacy ${name}`)};`);
  out.push(...block(':root', ['/* Legacy names for site/css/styles.css */', ...legacy]));

  return out.join('\n');
}

async function main() {
  const check = process.argv.includes('--check');
  const entries = await Promise.all(
    Object.entries(SOURCES).map(async ([key, rel]) => [key, await readJson(rel)]),
  );
  const files = Object.fromEntries(entries);
  const outputs = {
    [OUT]: buildCss(files),
    [FONTS_OUT]: buildFontsJs(files.primitives),
  };

  if (check) {
    let stale = false;
    for (const [rel, content] of Object.entries(outputs)) {
      let existing = '';
      try {
        existing = await readFile(path.join(ROOT, rel), 'utf8');
      } catch {
        // missing file counts as out of date
      }
      if (existing !== content) {
        console.error(`${rel} is out of date.`);
        stale = true;
      }
    }
    if (stale) {
      console.error('Run: node scripts/build-tokens.mjs');
      process.exit(1);
    }
    console.log(`${Object.keys(outputs).join(', ')} are up to date.`);
    return;
  }

  for (const [rel, content] of Object.entries(outputs)) {
    await writeFile(path.join(ROOT, rel), content);
    console.log(`Wrote ${rel} (${content.split('\n').length} lines)`);
  }
}

main().catch((err) => {
  console.error(err instanceof BuildError ? `Token error: ${err.message}` : err);
  process.exit(1);
});
